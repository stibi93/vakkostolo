import { URL } from 'node:url';
import process from 'node:process';
import { readFile, writeFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
import { loadDatabase } from './database-harness.mjs';

// Generate from the executed migrations' catalog, never by parsing SQL source text.
const db = new PGlite();
try {
  await loadDatabase(db);
  const { rows: columns } = await db.query(`select table_name, column_name, udt_name,
    is_nullable = 'YES' as nullable, column_default is not null as has_default
    from information_schema.columns where table_schema = 'public' order by table_name, ordinal_position`);
  const tables = [...new Set(columns.map((column) => column.table_name))];
  function type(name) {
    if (['uuid', 'text', 'timestamptz', 'timestamp with time zone'].includes(name)) return 'string';
    if (['int2', 'int4', 'int8', 'smallint', 'integer', 'bigint', 'numeric'].includes(name)) return 'number';
    if (['jsonb', 'json'].includes(name)) return 'Json';
    if (['bool', 'boolean'].includes(name)) return 'boolean';
    if (name === 'void') return 'undefined';
    if (tables.includes(name)) return `Database['public']['Tables']['${name}']['Row']`;
    throw new Error(`Unsupported database type: ${name}`);
  }
  const { rows: functions } = await db.query(`select p.proname as name,
    format_type(p.prorettype, null) as return_type, p.proretset as returns_set,
    p.pronargdefaults as defaults,
    coalesce((select json_agg(json_build_object('name', p.proargnames[n],
      'type', format_type(p.proargtypes[n-1], null)) order by n)
      from generate_series(1, p.pronargs) n), '[]'::json) as args
    from pg_proc p join pg_namespace s on p.pronamespace = s.oid
    where s.nspname = 'public' order by p.proname`);
  const lines = [
    '// Generated by npm run db:types from all migrations in PGlite. Do not edit.',
    '// Tables are typed here; Relationships are omitted because adapters use explicit RPCs.',
    'export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];',
    'export type Database = {', '  public: {', '    Tables: {',
  ];
  for (const table of tables) {
    lines.push(`      ${table}: {`);
    for (const mode of ['Row', 'Insert', 'Update']) {
      lines.push(`        ${mode}: {`);
      for (const column of columns.filter((c) => c.table_name === table)) {
        const optional = mode === 'Update' || (mode === 'Insert' && (column.nullable || column.has_default));
        lines.push(`          ${column.column_name}${optional ? '?' : ''}: ${type(column.udt_name)}${column.nullable ? ' | null' : ''};`);
      }
      lines.push('        };');
    }
    lines.push('        Relationships: [];', '      };');
  }
  lines.push('    };', '    Views: { [_ in never]: never };', '    Functions: {');
  for (const fn of functions) {
    const args = fn.args.map((arg, index) => `${arg.name}${index >= fn.args.length - fn.defaults ? '?' : ''}: ${type(arg.type)}`).join('; ');
    lines.push(`      ${fn.name}: { Args: ${args ? `{ ${args} }` : 'Record<never, never>'}; Returns: ${type(fn.return_type)}${fn.returns_set ? '[]' : ''} };`);
  }
  lines.push('    };', '    Enums: { [_ in never]: never };', '    CompositeTypes: { [_ in never]: never };', '  };', '};', '');
  const output = lines.join('\n');
  const target = new URL('../src/lib/database.types.ts', import.meta.url);
  if (process.argv.includes('--check')) {
    if (await readFile(target, 'utf8') !== output) throw new Error('Database types are stale. Run npm run db:types.');
  } else await writeFile(target, output);
} finally { await db.close(); }
